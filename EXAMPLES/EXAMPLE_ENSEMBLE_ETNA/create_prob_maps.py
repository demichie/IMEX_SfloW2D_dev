import numpy as np
import pandas as pd
from linecache import getline
from pathlib import Path

from output_layout import run_output_directory


def calculate_map(asc_file, category, row_list, group_index):

    n_rows = len(row_list)
    array_inv_tot = None
    c = 0

    for i in row_list:
        working_dir = Path(f"ensemble.{i:05d}")
        output_file = run_output_directory(working_dir) / category / asc_file
        if output_file.is_file():
            print(f"Reading .asc file: {output_file}")
            hdr = [getline(str(output_file), line) for line in range(1, 7)]
            values = [float(h.split(" ")[-1].strip()) for h in hdr]

            cols, rows, lx, ly, cell, nd = values
            cols = int(cols)
            rows = int(rows)

            array_inv = pd.read_table(output_file,
                                      delim_whitespace=True,
                                      header=None,
                                      skiprows=6,
                                      dtype='unicode').astype(float).values
            array_inv = np.flipud(array_inv)

            if array_inv_tot is None:
                array_inv_tot = np.zeros_like(array_inv)
            elif array_inv.shape != array_inv_tot.shape or (cols, rows) != (
                    array_inv_tot.shape[1], array_inv_tot.shape[0]):
                raise ValueError(f"inconsistent raster dimensions in {output_file}")
            array_inv_tot += (array_inv > 0)
        else:
            print(f"Missing solver raster: {output_file}")
            c += 1

    available = n_rows - c
    if array_inv_tot is None or available == 0:
        raise FileNotFoundError(f"no ensemble members produced {category}/{asc_file}")
    array_inv_tot = array_inv_tot / available
    array_inv_tot[array_inv_tot == 0.0] = nd

    result_dir = Path(f"result.{group_index:03d}")
    result_dir.mkdir(exist_ok=True)

    header = "ncols     %s\n" % cols
    header += "nrows    %s\n" % rows
    header += "xllcorner " + str(lx) + "\n"
    header += "yllcorner " + str(ly) + "\n"
    header += "cellsize " + str(cell) + "\n"
    header += "NODATA_value " + str(nd)

    np.savetxt(result_dir / asc_file,
               np.flipud(array_inv_tot),
               header=header,
               fmt='%1.5f',
               comments='')


